import Foundation

public enum RiskLevel: String, Codable, Sendable {
    case safe        // regenerated automatically
    case caution     // user may lose convenience/data (history, caches that are slow to rebuild)
    case advisory    // user data; never pre-selected
}

public enum CategoryGroup: String, CaseIterable, Sendable {
    case common = "Common"
    case developer = "Developer"
    case privacyAndUserData = "Privacy & User Data"
    case advisory = "Advisory"
}

public enum JunkCategory: String, CaseIterable, Codable, Identifiable, Hashable, Sendable {
    case systemCaches, appCaches, logs, tempFiles, trash,
         browserData, appRemnants, developerJunk, iOSBackups,
         languageFiles, brokenPrefs, downloadJunk, duplicates,
         dsStore, fontCaches, quickLookCaches, mailJunk,
         packageManagers, notificationHistory, spotlightExternal,
         iCloudConflicts, screenshots, vmDockerLeftovers, timeMachineSnapshots

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .systemCaches: "System Caches"
        case .appCaches: "App Caches"
        case .logs: "Log Files"
        case .tempFiles: "Temporary Files"
        case .trash: "Trash"
        case .browserData: "Browser Data"
        case .appRemnants: "App Leftovers"
        case .developerJunk: "Developer Cache"
        case .iOSBackups: "iPhone & iPad Backups"
        case .languageFiles: "Unused Language Files"
        case .brokenPrefs: "Orphaned Preferences"
        case .downloadJunk: "Downloads Junk"
        case .duplicates: "Duplicate Files"
        case .dsStore: ".DS_Store Files"
        case .fontCaches: "Font Caches"
        case .quickLookCaches: "Quick Look Thumbnails"
        case .mailJunk: "Mail Attachments & Junk"
        case .packageManagers: "Package Manager Caches"
        case .notificationHistory: "Notification History"
        case .spotlightExternal: "Spotlight Index Files"
        case .iCloudConflicts: "iCloud Conflicts"
        case .screenshots: "Old Screenshots"
        case .vmDockerLeftovers: "VM & Docker Leftovers"
        case .timeMachineSnapshots: "Local Time Machine Snapshots"
        }
    }

    public var summary: String {
        switch self {
        case .systemCaches: "Cached data from the system that is regenerated automatically. Safe to delete."
        case .appCaches: "Cached data from apps that is regenerated automatically. Safe to delete."
        case .logs: "Diagnostic logs written by apps and the OS. Safe to delete."
        case .tempFiles: "Short-lived files created by apps and the OS."
        case .trash: "Files you've already deleted but haven't emptied from the Trash."
        case .browserData: "Browsing history, cookies and offline page cache from web browsers."
        case .appRemnants: "Support files, caches and preferences left by apps you've already uninstalled."
        case .developerJunk: "Large caches created by Xcode, simulators and other developer tools."
        case .iOSBackups: "Local backups of iOS devices. Can be very large (1–50+ GB each)."
        case .languageFiles: "App bundles include translations for all languages; unused ones waste space."
        case .brokenPrefs: "Preference files left by apps that are no longer installed."
        case .downloadJunk: "Old installers, disk images and duplicate downloads."
        case .duplicates: "Identical files taking up space twice."
        case .dsStore: "Hidden Finder folder metadata. Safe to delete; Finder recreates it."
        case .fontCaches: "Font registry caches that can grow stale."
        case .quickLookCaches: "Thumbnail previews generated by Quick Look. Regenerated on demand."
        case .mailJunk: "Downloaded Mail attachments and Mail caches."
        case .packageManagers: "Cached downloads from Homebrew, npm, pip, Cargo and similar tools."
        case .notificationHistory: "Stored Notification Center history database."
        case .spotlightExternal: "Hidden Spotlight metadata on external drives."
        case .iCloudConflicts: "Conflicting copies of iCloud files."
        case .screenshots: "Screenshots accumulate quickly on the Desktop."
        case .vmDockerLeftovers: "Disk images and data from virtual machines and Docker."
        case .timeMachineSnapshots: "Local snapshots APFS keeps for Time Machine."
        }
    }

    public var isEnabledByDefault: Bool {
        switch self {
        case .systemCaches, .appCaches, .logs, .tempFiles, .trash, .appRemnants,
             .brokenPrefs, .dsStore, .fontCaches, .quickLookCaches,
             .spotlightExternal, .iCloudConflicts, .languageFiles:
            true
        case .browserData, .developerJunk, .iOSBackups, .downloadJunk, .duplicates,
             .mailJunk, .packageManagers, .notificationHistory, .screenshots,
             .vmDockerLeftovers, .timeMachineSnapshots:
            false
        }
    }

    public var requiresFullDiskAccess: Bool {
        switch self {
        case .notificationHistory, .timeMachineSnapshots: true
        default: false
        }
    }

    /// Whether part of the category needs Full Disk Access (system-level paths); those parts are skipped without it.
    public var partiallyRequiresFullDiskAccess: Bool {
        switch self {
        case .systemCaches, .logs, .tempFiles, .trash, .fontCaches: true
        default: false
        }
    }

    public var risk: RiskLevel {
        switch self {
        case .iOSBackups, .duplicates, .downloadJunk, .mailJunk, .vmDockerLeftovers, .screenshots:
            .advisory
        case .browserData, .developerJunk, .timeMachineSnapshots, .notificationHistory, .languageFiles:
            .caution
        default:
            .safe
        }
    }

    /// Advisory categories must never have files pre-selected.
    public var selectsFilesByDefault: Bool { risk != .advisory }

    public var group: CategoryGroup {
        switch self {
        case .systemCaches, .appCaches, .logs, .tempFiles, .trash, .appRemnants, .brokenPrefs,
             .dsStore, .fontCaches, .quickLookCaches, .spotlightExternal, .languageFiles:
            .common
        case .developerJunk, .packageManagers:
            .developer
        case .browserData, .notificationHistory, .iCloudConflicts, .screenshots, .downloadJunk:
            .privacyAndUserData
        case .iOSBackups, .duplicates, .mailJunk, .vmDockerLeftovers, .timeMachineSnapshots:
            .advisory
        }
    }

    /// Warning to show before cleaning this category, if any.
    public var warning: String? {
        switch self {
        case .browserData: "This will log you out of websites and remove saved passwords if the browser is configured that way."
        case .iOSBackups: "These are your iPhone/iPad backups. Deleting them means you cannot restore your device to this point."
        case .vmDockerLeftovers: "Virtual machine disk images contain entire operating systems. Only delete if you no longer need this VM."
        case .timeMachineSnapshots: "Local snapshots are used to recover files when the Time Machine disk is unavailable."
        case .notificationHistory: "Notifications will be cleared from Notification Center history."
        case .fontCaches: "Font caches will rebuild on next login. You may want to restart your Mac."
        case .languageFiles: "Some apps may need to be relaunched."
        default: nil
        }
    }

    public static var defaultEnabled: Set<JunkCategory> {
        Set(allCases.filter(\.isEnabledByDefault))
    }
}
